import java.lang.Math;
class MathDemo
{
	public static void  main(String args[])
	{
		System.out.println("the power is : "+Math.pow(2,3));
		System.out.println("the square root is : "+Math.sqrt(24));
		System.out.println("the absolute value is : "+Math.abs(-24));
		System.out.println("the maximum value is : "+Math.max(24,33));
		System.out.println("the minimum value is : "+Math.min(24,2));
		System.out.println("random value is : "+Math.random());
	}
}