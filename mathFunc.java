import java.lang.Math;
class mathFunc
{
	public static void main(String args[])
	{
		
		System.out.println("square root is "+Math.sqrt(3));
		System.out.println("power is root is "+Math.pow(3,2));
		System.out.println("minimum value is "+Math.min(3,2));
		System.out.println("maximum value is "+Math.max(3,2));
		System.out.println("random value is "+Math.random());
		System.out.println("log value is "+Math.log(5));
		System.out.println("log 10 value is "+Math.log10(10));
		System.out.println("absolute value is "+Math.abs(-5));
		System.out.println("exponent value is "+Math.exp(5));
		
		
	}	
}