import java.lang.*;
import static java.lang.Math.*;
class StaticImportDemo
{
	public static void main(String args[])
	{
		System.out.println("Square root is : "+sqrt(25));
		System.out.println("power is : "+pow(2,5));
		System.out.println("absolute value is : "+abs(3));
		System.out.println("random value is : "+random());
	}
}