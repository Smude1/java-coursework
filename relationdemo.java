class relationdemo
{
	public static void main(String args[])
	{
		int a=34,b=5;
		System.out.println("answer is : "+(a<b)); 
		System.out.println("answer is : "+(a>b));
		System.out.println("answer is : "+(a<=b));
		System.out.println("answer is : "+(a>=b));
		System.out.println("answer is : "+(a==b));
		System.out.println("answer is : "+(a!=b));
	}
}